# =============================================================================
# LAYER & MATERIAL NAMES
# =============================================================================
LAYER_COLUMNS  = "STR-Columns"
LAYER_BEAMS    = "STR-Beams"
LAYER_SLABS    = "STR-Slabs"
LAYER_BRACES   = "STR-Braces"
LAYER_WALLS    = "STR-Walls"
LAYER_FOUND    = "STR-Foundations"
LAYER_UNMAPPED = "LOD300_UNMAPPED_NEEDS_REVIEW"

